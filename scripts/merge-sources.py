#!/usr/bin/env python3
"""Regenerate docs/sources.md from the Sources tables in research/*.md.

Each research file ends with a table in the source-logging skill's row format:
| ID | Claim / number | Value | Publisher | URL | Published | Accessed | Used in |
This script collects every such row, keeps the file's own id (M12, C4, P88...) in a column so the
report can cite either, and assigns a global S-number in file order.

Usage: python3 scripts/merge-sources.py   (from the repo root)
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESEARCH = ROOT / "research"
OUT = ROOT / "docs" / "sources.md"

# Order matters: ids are assigned in this order, so numbering is stable as files are appended.
FILES = [
    "market-sizing.md",
    "hobby-immersion.md",
    "competitors.md",
    "monetization.md",
    "infrastructure-and-data.md",
    "gap-analysis.md",
    "evidence-repair-shop-tool.md",
    "evidence-private-logbook.md",
    "red-team.md",
    "../docs/validation-gate.md",
    "../docs/product-definition.md",
]

ROW = re.compile(r"^\|\s*([A-Z]{1,2}\d+[a-z]?)\s*\|(.*)\|\s*$")
HEADER_WORDS = ("claim", "value", "publisher", "url")


def source_rows(text: str) -> list[tuple[str, str]]:
    """Return (local id, rest-of-row) for rows in the file's Sources section(s)."""
    rows: list[tuple[str, str]] = []
    in_sources = False
    for line in text.splitlines():
        if line.startswith("## "):
            in_sources = "source" in line.lower()
            continue
        if not in_sources:
            continue
        m = ROW.match(line)
        if not m:
            continue
        rest = m.group(2)
        if all(w in rest.lower() for w in HEADER_WORDS):
            continue  # header row
        if set(rest.replace("|", "").strip()) <= {"-", " ", ":"}:
            continue  # separator row
        rows.append((m.group(1), rest.strip()))
    return rows


def main() -> None:
    out: list[str] = []
    out.append("# Source log\n")
    out.append(
        "Every number or claim used in the report, with where it came from. Generated by\n"
        "`scripts/merge-sources.py` from the `Sources` tables at the end of each `research/*.md`\n"
        "file; edit those, not this file. Format follows `.claude/skills/source-logging`.\n"
    )
    out.append(
        "Rules: a number with no URL is labelled **estimate** and shows its derivation. Access dates\n"
        "are UTC. \"Published\" is the document's own date, or the data year if that's all it gives.\n"
    )
    table: list[str] = []
    n = 0
    per_file: list[tuple[str, int]] = []
    for name in FILES:
        path = RESEARCH / name
        if not path.exists():
            continue
        rows = source_rows(path.read_text(encoding="utf-8"))
        per_file.append((name, len(rows)))
        for local_id, rest in rows:
            n += 1
            cells = [c.strip() for c in rest.split("|")]
            # Pad or trim to the 7 expected columns after the id.
            cells = (cells + [""] * 7)[:7]
            table.append(f"| S{n} | {local_id} | {name} | " + " | ".join(cells) + " |")
    summary = ", ".join(f"{name} {count}" for name, count in per_file)
    out.append(f"Rows: {n} ({summary}).\n")
    out.append("| S | Local id | File | Claim / number | Value | Publisher | URL | Published | Accessed | Used in |")
    out.append("|---|----------|------|----------------|-------|-----------|-----|-----------|----------|---------|")
    out.extend(table)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} with {n} rows: {summary}")


if __name__ == "__main__":
    main()
